-- Secure documents library + work sites/credentials.
create table if not exists public.document_categories(
 id bigint generated by default as identity primary key,
 title text not null check(length(btrim(title)) between 1 and 160), description text,
 sort_order integer not null default 0, created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create index if not exists document_categories_sort_idx on public.document_categories(sort_order,id);

create table if not exists public.documents(
 id bigint generated by default as identity primary key,
 category_id bigint not null references public.document_categories(id) on delete cascade,
 title text not null check(length(btrim(title)) between 1 and 220), description text,
 original_file_name text not null check(length(btrim(original_file_name)) between 1 and 512),
 storage_path text not null unique, mime_type text not null, file_size bigint not null check(file_size>=0),
 version integer not null default 1 check(version>0), created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create index if not exists documents_category_idx on public.documents(category_id,created_at desc);
create index if not exists documents_title_idx on public.documents(lower(title));

create or replace function private.is_safe_http_url(p_url text) returns boolean
language sql immutable set search_path='' as $$
 select coalesce(p_url ~* '^https?://[^[:space:]/?#]+(?::[0-9]{1,5})?(?:[/?#][^[:space:]]*)?$',false)
$$;

create table if not exists public.site_definitions(
 id bigint generated by default as identity primary key,
 kind text not null check(kind in('organization','personal')),
 owner_user_id uuid references public.profiles(id) on delete cascade,
 title text not null check(length(btrim(title)) between 1 and 200),
 url text not null check(private.is_safe_http_url(url)), description text, category text, icon text,
 scope text not null default 'all' check(scope in('all','selected','owner')), active boolean not null default true,
 created_by uuid not null references public.profiles(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 constraint site_definition_kind_scope_check check(
  (kind='organization' and owner_user_id is null and scope in('all','selected')) or
  (kind='personal' and owner_user_id is not null and scope='owner')));
create index if not exists site_definitions_kind_idx on public.site_definitions(kind,active,id);
create index if not exists site_definitions_owner_idx on public.site_definitions(owner_user_id) where owner_user_id is not null;

create table if not exists public.site_assignments(
 site_id bigint not null references public.site_definitions(id) on delete cascade,
 user_id uuid not null references public.profiles(id) on delete cascade,
 created_at timestamptz not null default now(), primary key(site_id,user_id));
create index if not exists site_assignments_user_idx on public.site_assignments(user_id,site_id);

create table if not exists public.user_site_credentials(
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 site_id bigint not null references public.site_definitions(id) on delete cascade,
 username_ciphertext text not null, username_iv text not null,
 password_ciphertext text not null, password_iv text not null,
 key_version smallint not null default 1 check(key_version>0), notes text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique(user_id,site_id));
create index if not exists user_site_credentials_user_idx on public.user_site_credentials(user_id,site_id);

create table if not exists public.security_audit_log(
 id bigint generated by default as identity primary key,
 user_id uuid references public.profiles(id) on delete set null,
 action text not null, target_type text not null, target_id text,
 metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now());
create index if not exists security_audit_user_idx on public.security_audit_log(user_id,created_at desc);
create index if not exists security_audit_action_idx on public.security_audit_log(action,created_at desc);

