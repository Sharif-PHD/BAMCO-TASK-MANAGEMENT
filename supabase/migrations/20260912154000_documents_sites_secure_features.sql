-- A random AES-256 key is created server-side only. The actual value is never committed.
do $$begin
 if not exists(select 1 from vault.secrets where name='bamco_credential_aes_key') then
  perform vault.create_secret(encode(extensions.gen_random_bytes(32),'base64'),'bamco_credential_aes_key','AES-256-GCM key for BAMCO site credentials; server-only');
 end if;
end$$;
create or replace function public.credential_server_key() returns text language plpgsql stable security definer set search_path='' as $$
declare v_key text;begin
 if auth.role()<>'service_role' then raise exception 'دسترسی مجاز نیست';end if;
 select decrypted_secret into v_key from vault.decrypted_secrets where name='bamco_credential_aes_key' limit 1;
 if v_key is null then raise exception 'کلید رمزنگاری تنظیم نشده است';end if;return v_key;
end$$;
revoke all on function public.credential_server_key() from public,anon,authenticated;
grant execute on function public.credential_server_key() to service_role;
