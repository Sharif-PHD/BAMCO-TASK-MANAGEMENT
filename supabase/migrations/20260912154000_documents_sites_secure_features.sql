create or replace function private.write_feature_audit(p_user uuid,p_action text,p_target_type text,p_target_id text,p_metadata jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path='' as $$
begin insert into public.security_audit_log(user_id,action,target_type,target_id,metadata)
values(p_user,p_action,p_target_type,p_target_id,coalesce(p_metadata,'{}'::jsonb));end $$;
revoke all on function private.write_feature_audit(uuid,text,text,text,jsonb) from public,anon,authenticated;

create or replace function private.audit_category_changes() returns trigger language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid();begin
 if auth.role()='service_role' then if tg_op='DELETE' then return old;else return new;end if;end if;
 if tg_op='INSERT' then perform private.write_feature_audit(actor,'category_create','document_category',new.id::text,jsonb_build_object('title',new.title));return new;
 elsif tg_op='UPDATE' then perform private.write_feature_audit(actor,'category_update','document_category',new.id::text,jsonb_build_object('title',new.title));return new;
 else perform private.write_feature_audit(actor,'category_delete','document_category',old.id::text,jsonb_build_object('title',old.title));return old;end if;
end $$;
drop trigger if exists document_categories_audit on public.document_categories;
create trigger document_categories_audit after insert or update or delete on public.document_categories for each row execute function private.audit_category_changes();

create or replace function private.audit_site_changes() returns trigger language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid();begin
 if auth.role()='service_role' then if tg_op='DELETE' then return old;else return new;end if;end if;
 if tg_op='INSERT' then perform private.write_feature_audit(actor,'site_create','site_definition',new.id::text,jsonb_build_object('kind',new.kind,'title',new.title));return new;
 elsif tg_op='UPDATE' then perform private.write_feature_audit(actor,'site_update','site_definition',new.id::text,jsonb_build_object('kind',new.kind,'title',new.title));return new;
 else perform private.write_feature_audit(actor,'site_delete','site_definition',old.id::text,jsonb_build_object('kind',old.kind,'title',old.title));return old;end if;
end $$;
