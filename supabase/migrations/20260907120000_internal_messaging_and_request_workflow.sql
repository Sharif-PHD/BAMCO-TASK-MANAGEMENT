drop policy if exists "managers manage message templates" on public.message_templates;
create policy "managers manage message templates" on public.message_templates for all to authenticated using ((select private.is_manager())) with check ((select private.is_manager()));
insert into public.message_templates(template_key,body_text)
select template_key,coalesce(body_html,'') from public.email_templates
where to_regclass('public.email_templates') is not null
on conflict(template_key) do nothing;

